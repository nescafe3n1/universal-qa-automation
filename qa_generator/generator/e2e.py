"""
Writers for tests/e2e/*.py (browser tests).

Rule for every generated test: if the scan found something, the test asserts it
hard. Nothing is wrapped in "if it exists" — a missing element is a failure.
Templates use __TOKEN__ placeholders (filled with Python literals via py()) so
the test code below reads like normal Python.
"""

from urllib.parse import urlparse

from qa_generator.config import MAX_E2E_ROUTE_TESTS, TABLE_SELECTOR
from qa_generator.generator.context import SuiteContext
from qa_generator.scanner.components import _visible_variant
from qa_generator.scanner.standalone import PROBE
from qa_generator.templates.qa_login import is_login_url
from qa_generator.utils import UniqueNamer, css_attr, path_of, py, same_site


def fill(template: str, **values) -> str:
    for key, value in values.items():
        template = template.replace(f"__{key}__", py(value))
    return template


def header(doc: str, ctx: SuiteContext, imports: str, markers: str) -> str:
    return (
        f'"""\n{doc}\n\nGenerated by Nes-Dev QA from a live scan of {ctx.target_url}\n"""\n\n'
        f"{imports}\n\npytestmark = {markers}\n"
    )


PAGE_IMPORTS = "import re\n\nimport pytest\nfrom playwright.sync_api import Page, expect\n\nfrom qa_forms import text_re"
AUTH_IMPORTS = PAGE_IMPORTS + "\n\nfrom qa_login import LOGOUT_SELECTOR, access_blocked, is_login_url, password_field_visible"


FORM_IMPORTS = ("\n\nfrom qa_forms import (SUBMIT_BUTTON, check_empty_submit, check_valid_submit,\n"
                "                      fill_form, submit_and_observe)")


def write_e2e_tests(ctx: SuiteContext) -> None:
    write_navigation(ctx)
    write_components(ctx)
    write_interactions(ctx)
    write_accessibility(ctx)
    write_forms(ctx)
    write_user_session(ctx)
    write_admin_portal(ctx)
    write_access_control(ctx)


