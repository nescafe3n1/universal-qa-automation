def sent_to_login(link: dict, login_url: str = None) -> bool:
    """True if the scan saw this link redirect a guest to the login page (so the status seen was the login page's)."""
    final, own = link.get("final_url") or "", link.get("full_url") or ""
    if not final:
        return False
    if login_url and is_login_url(final, login_url) and not is_login_url(own, login_url):
        return True
    return "login" in urlparse(final).path.lower() and "login" not in urlparse(own).path.lower()


def write_accessibility(ctx: SuiteContext) -> None:
    """One test per scanned public page: no NEW critical or serious accessibility problems (existing ones are shown as a warning)."""
    pages = ctx.scan.get("accessibility") or []
    if not pages:
        return
    namer = UniqueNamer()
    rows = [(namer(path_of(p["page_url"]).strip("/").replace("/", "_") or "home", "page"), p["page_url"],
             sorted(v["id"] for v in p["violations"])) for p in pages]
    code = header("Accessibility (axe-core, WCAG 2 A and AA): no NEW critical or serious problems on each scanned page. "
                  "Problems that already existed when the site was scanned are listed as a warning, not a failure.",
                  ctx, PAGE_IMPORTS + "\n\nfrom qa_a11y import describe, serious_violations", "pytest.mark.e2e")
    code += fill('''

PAGES = __PAGES__


@pytest.mark.parametrize("url, known", [p[1:] for p in PAGES], ids=[p[0] for p in PAGES])
def test_accessibility_serious_issues(page: Page, url: str, known: list):
    """Verify the page has no new critical or serious accessibility problems (WCAG 2 A and AA, checked with axe-core)."""
    page.goto(url)
    found = serious_violations(page)
    new = {rule: details for rule, details in found.items() if rule not in known}
    assert not new, "New accessibility problems: " + describe(new)
    if found:
        pytest.skip("WARNING: existing accessibility problems, already there when the site was scanned: " + describe(found))
''', PAGES=rows)
    ctx.write_test("e2e", "test_accessibility.py", code)


def _is_guest_html_page(link: dict) -> bool:
    status, content_type = link.get("status"), link.get("content_type") or ""
    return (status is None or status < 400) and (not content_type or "html" in content_type) and not sent_to_login(link)
