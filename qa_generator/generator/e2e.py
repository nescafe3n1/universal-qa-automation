def write_components(ctx: SuiteContext) -> None:
    comp = ctx.scan["components"]
    parts = []
    namer = UniqueNamer()

    for card in comp.get("all_cards") or []:
        name = namer(card["type"], "group")
        parts.append(fill('''

def test_repeating_content_items_''' + name + '''(page: Page):
    """Verify a group of repeating content items renders (at least two visible)."""
    page.goto(__URL__)
    items = page.locator(__SEL__)
    expect(items.nth(1)).to_be_visible()
''', URL=card["page_url"], SEL=_visible_variant(card["selector"])))

    search = comp.get("search")
    if search:
        cards_here = next((c for c in comp.get("all_cards") or [] if c["page_url"] == search["page_url"]), None)
        queries = search.get("queries") or [search["sample_query"]]
        body = fill('''

@pytest.mark.parametrize("query", __QUERIES__)
def test_search_input_filtering(page: Page, query: str):
    """Verify the search box accepts a query and a nonsense query does not show more results."""
    page.goto(__URL__)
    box = page.locator(__SEL__).first
    expect(box).to_be_editable()
    box.fill(query)
    expect(box).to_have_value(query)
''', URL=search["page_url"], SEL=search["selector"], QUERIES=queries)
        if cards_here:
            body += fill('''    items = page.locator(__ITEMS__)
    page.wait_for_timeout(800)
    positive = items.count()
    assert positive >= 1, f"Searching for {query!r}, a word from an existing item, shows no items"
    box.fill(__NEG__)
    expect(box).to_have_value(__NEG__)
    page.wait_for_timeout(800)
    assert items.count() <= positive, "Nonsense search query shows more items than a real query"
''', ITEMS=_visible_variant(cards_here["selector"]), NEG=search["negative_query"])
        else:
            body += fill('''    box.fill(__NEG__)
    expect(box).to_have_value(__NEG__)
''', NEG=search["negative_query"])
        parts.append(body)

    for flt in (comp.get("filters") or [])[:8]:
        name = namer(flt["text"], "filter")
        if flt.get("type") == "select":
            parts.append(fill('''

@pytest.mark.parametrize("value", __VALUES__)
def test_filter_dropdown_''' + name + '''(page: Page, value: str):
    """Verify the filter dropdown can be changed to each of its options."""
    errors = []
    page.on("pageerror", lambda err: errors.append(str(err)))
    page.goto(__URL__)
    select = page.locator(__SEL__).first
    expect(select).to_be_visible()
    start_url = page.url
    select.select_option(value)
    page.wait_for_timeout(500)
    assert not errors, f"Choosing {value!r} threw JavaScript errors: {errors}"
    if page.url == start_url:  # some dropdowns submit and reload the page instead
        expect(select).to_have_value(value)
''', URL=flt["page_url"], SEL=flt["selector"], VALUES=flt.get("values") or [flt["sample_value"]]))
        else:
            parts.append(fill('''

def test_filter_control_''' + name + '''(page: Page):
    """Verify the filter button/tab can be clicked without errors and reports its state."""
    errors = []
    page.on("pageerror", lambda err: errors.append(str(err)))
    page.goto(__URL__)
    control = page.locator(__SEL__).filter(has_text=text_re(__TEXT__)).first
    expect(control).to_be_visible()
    start_url = page.url
    control.click()
    page.wait_for_timeout(500)
    assert not errors, f"Clicking the filter threw errors: {errors}"
    if page.url == start_url:
        for attr in ("aria-selected", "aria-pressed"):
            if control.get_attribute(attr) is not None:
                expect(control).to_have_attribute(attr, "true")
                break
''', URL=flt["page_url"], SEL=flt["selector"], TEXT=flt["text"]))

    modal = comp.get("modal")
    if modal:
        trig = modal["trigger"]
        trigger_expr = "page.locator(__TRIG__)"
        if trig.get("text"):
            trigger_expr += '.filter(has_text=text_re(__TTEXT__))'
        body = fill('''

def test_interactive_modal_dialog(page: Page):
    """Verify the dialog opens when its trigger is clicked''' + (" and closes again" if modal.get("close_method") else "") + '''."""
    page.goto(__URL__)
    trigger = ''' + trigger_expr + '''.first
    expect(trigger).to_be_visible()
    trigger.click()
    dialog = page.locator(__DLG__).first
    expect(dialog).to_be_visible()
''', URL=modal["page_url"], TRIG=trig["selector"], TTEXT=trig.get("text") or "", DLG=modal["dialog_selector"])
        if modal.get("close_method") == "button":
            body += fill('''    dialog.locator(__CLOSE__).first.click()
    expect(page.locator(__DLG__)).to_have_count(0)
''', CLOSE=modal["close_selector"], DLG=modal["dialog_selector"])
        elif modal.get("close_method") == "escape":
            body += fill('''    page.keyboard.press("Escape")
    expect(page.locator(__DLG__)).to_have_count(0)
''', DLG=modal["dialog_selector"])
        parts.append(body)

    tables = comp.get("tables") or []
    if tables:
        tbl = tables[0]
        body = fill('''

def test_data_table_rendered(page: Page):
    """Verify the data table renders with its column headers."""
    page.goto(__URL__)
    table = page.locator(__SEL__).first
    expect(table).to_be_visible()
''', URL=tbl["page_url"], SEL=_visible_variant(TABLE_SELECTOR))
        if tbl.get("headers"):
            body += fill('''    expect(table).to_contain_text(__H__)
''', H=tbl["headers"][0])
        parts.append(body)

    if not parts:
        return
    code = header("Components discovered on the site: repeating items, search, filters, dialogs, tables.",
                  ctx, PAGE_IMPORTS, "pytest.mark.e2e")
    ctx.write_test("e2e", "test_components.py", code + "".join(parts))


