def write_navigation(ctx: SuiteContext) -> None:
    hp = ctx.scan["homepage"]
    # Browser tests only visit links that served an HTML page to a guest during the scan
    # (no auth-protected pages, no file downloads).
    links = [lk for lk in hp.get("nav_links", []) if _is_guest_html_page(lk)]
    code = header("Homepage, navigation links, public pages, mobile layout and console errors.",
                  ctx, PAGE_IMPORTS, "pytest.mark.e2e")

    title = hp.get("title", "")
    title_snippet = title.split(" - ")[0].split("|")[0].strip() or title.strip()
    code += fill('''

@pytest.mark.smoke
def test_homepage_title_and_hero(page: Page, base_url: str):
    """Verify the homepage loads with its title and main heading."""
    response = page.goto(base_url)
    assert response is not None and response.status < 400, f"Homepage returned {response.status if response else 'no response'}"
''')
    if title_snippet:
        code += fill('''    expect(page).to_have_title(re.compile(re.escape(__T__), re.IGNORECASE))
''', T=title_snippet)
    if hp.get("heading"):
        code += '''    expect(page.locator("h1, [role='heading'][aria-level='1'], h2").first).to_be_visible()
'''

    # Primary call-to-action
    cta = hp.get("primary_cta")
    if cta and not cta.get("new_tab"):
        sel = cta["selector"] + ":visible"
        if same_site(cta["full_url"], ctx.target_url) and (urlparse(cta["full_url"]).path or "/") not in ("", "/"):
            code += fill('''

def test_primary_cta_navigates(page: Page, base_url: str):
    """Verify the primary call-to-action button opens its target page."""
    page.goto(base_url)
    cta = page.locator(__SEL__).first
    expect(cta).to_be_visible()
    cta.click()
    expect(page).to_have_url(re.compile(re.escape(__PATH__)))
''', SEL=sel, PATH=urlparse(cta["full_url"]).path)
        else:
            code += fill('''

def test_primary_cta_visible(page: Page, base_url: str):
    """Verify the primary call-to-action button is shown."""
    page.goto(base_url)
    expect(page.locator(__SEL__).first).to_be_visible()
''', SEL=sel)

    # Skip link (accessibility)
    skip = hp.get("skip_link")
    if skip:
        code += fill('''

def test_skip_link_target_exists(page: Page, base_url: str):
    """Verify the skip-to-content link points at an element that exists."""
    page.goto(base_url)
    expect(page.locator(__LINK__).first).to_be_attached()
    expect(page.locator(__TARGET__).first).to_be_attached()
''', LINK=f"a{css_attr('href', skip['href'])}",
            TARGET=f"{css_attr('id', skip['target_id'])}, a{css_attr('name', skip['target_id'])}")

    # Clickable, visible navigation links
    namer = UniqueNamer()
    clicks = [
        (namer(lk["name"], "link"), f"a{css_attr('href', lk['href'])}:visible", lk["route"])
        for lk in links
        if lk.get("href") and lk.get("visible") and not lk.get("new_tab") and lk["route"] not in ("", "/")
    ][:MAX_E2E_ROUTE_TESTS]
    if clicks:
        code += fill('''

NAV_CLICKS = __CLICKS__


@pytest.mark.parametrize("selector, route", [c[1:] for c in NAV_CLICKS], ids=[c[0] for c in NAV_CLICKS])
def test_nav_link_navigates(page: Page, base_url: str, selector: str, route: str):
    """Verify clicking a navigation link opens its page."""
    page.goto(base_url)
    link = page.locator(selector).first
    expect(link).to_be_visible()
    link.click()
    expect(page).to_have_url(re.compile(re.escape(route)))
''', CLICKS=clicks)

    # Public pages load
    namer = UniqueNamer()
    routes = [(namer(lk["name"], "page"), lk["full_url"]) for lk in links][:MAX_E2E_ROUTE_TESTS]
    if routes:
        code += fill('''

PUBLIC_PAGES = __ROUTES__


@pytest.mark.parametrize("url", [p[1] for p in PUBLIC_PAGES], ids=[p[0] for p in PUBLIC_PAGES])
def test_public_route_loads(page: Page, url: str):
    """Verify a public page loads without an error status."""
    response = page.goto(url)
    assert response is not None and response.status < 400, f"{url} returned {response.status if response else 'no response'}"
    expect(page.locator("body")).to_be_visible()
''', ROUTES=routes)

    code += '''

def test_mobile_responsive_layout(page: Page, base_url: str):
    """Verify the homepage fits a 375px mobile screen without horizontal scrolling."""
    page.set_viewport_size({"width": 375, "height": 667})
    page.goto(base_url)
    expect(page.locator("body")).to_be_visible()
    overflow = page.evaluate("""() => {
        const d = document.documentElement, b = document.body;
        const clipped = el => ['hidden', 'clip'].includes(getComputedStyle(el).overflowX);
        return (clipped(d) || clipped(b)) ? 0 : d.scrollWidth - d.clientWidth;
    }""")
    assert overflow <= 2, f"Page is {overflow}px wider than a 375px phone screen (horizontal scrolling)"


def test_no_critical_console_errors(page: Page, base_url: str):
    """Verify the homepage throws no uncaught JavaScript exceptions."""
    errors = []
    page.on("pageerror", lambda err: errors.append(str(err)))
    page.goto(base_url)
    page.wait_for_timeout(1000)
    assert not errors, f"Page threw uncaught exceptions: {errors}"
'''
    ctx.write_test("e2e", "test_navigation.py", code)


