def write_admin_portal(ctx: SuiteContext) -> None:
    session = ctx.scan.get("admin_session")
    if not (ctx.admin_acc and session):
        return
    admin_forms = _fillable(session.get("forms"))
    code = header("Logged-in administrator: dashboard, admin sub-pages and forms.", ctx,
                  AUTH_IMPORTS + (FORM_IMPORTS if admin_forms else ""), "[pytest.mark.e2e, pytest.mark.auth]")
    code += fill('''
ADMIN_LANDING = __LANDING__


def test_admin_login_and_dashboard(login_admin: Page, login_url: str):
    """Verify the administrator can log in and open the dashboard."""
    page = login_admin
    response = page.goto(ADMIN_LANDING)
    assert response is None or response.status < 400, f"Dashboard returned {response.status}"
    assert not is_login_url(page.url, login_url), "Redirected to login when opening the dashboard"
''', LANDING=ctx.admin_target_url)
    if session.get("has_heading"):
        code += '''    expect(page.locator("h1, h2").first).to_be_visible()
'''

    namer = UniqueNamer()
    pages = [
        (namer(sp["path"].replace("/", "_"), "page"), sp["url"], sp["has_heading"], sp["has_table"])
        for sp in session.get("subpages", [])
        if sp.get("status") is None or sp["status"] < 400
    ]
    if pages:
        code += fill('''

ADMIN_PAGES = __PAGES__


@pytest.mark.parametrize("url, has_heading, has_table", [p[1:] for p in ADMIN_PAGES], ids=[p[0] for p in ADMIN_PAGES])
def test_admin_subpage(login_admin: Page, login_url: str, url: str, has_heading: bool, has_table: bool):
    """Verify an admin page opens for the administrator and shows what the scan saw."""
    page = login_admin
    response = page.goto(url)
    assert response is None or response.status < 400, f"{url} returned {response.status}"
    assert not is_login_url(page.url, login_url), f"Redirected to login from {url}"
    if has_heading:
        expect(page.locator("h1, h2").first).to_be_visible()
    if has_table:
        expect(page.locator("table:visible, [role='table']:visible").first).to_be_visible()
''', PAGES=pages)
    code += _logged_in_form_tests(ctx, admin_forms, "login_admin", "admin_form")
    ctx.write_test("e2e", "test_admin_portal.py", code)


