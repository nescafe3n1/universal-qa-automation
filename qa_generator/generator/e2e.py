def write_user_session(ctx: SuiteContext) -> None:
    session = ctx.scan.get("user_session")
    if not (ctx.user_acc and session):
        return
    user_forms = _fillable(session.get("forms"))
    code = header("Logged-in standard user: login, account pages, forms, logout.", ctx,
                  AUTH_IMPORTS + (FORM_IMPORTS if user_forms else ""), "[pytest.mark.e2e, pytest.mark.auth]")
    code += fill('''
USER_LANDING = __LANDING__
''', LANDING=ctx.user_target_url)

    code += '''

def test_user_login_success(login_user: Page, login_url: str):
    """Verify the user can log in and the login form goes away."""
    page = login_user
    assert not password_field_visible(page), "Password field still visible after login"
'''
    if not is_login_url(session["post_login_url"], ctx.login_url):
        code += '''    assert not is_login_url(page.url, login_url), f"Still on a login URL after login: {page.url}"
'''

    namer = UniqueNamer()
    pages = [(namer(lk["name"], "page"), lk["url"]) for lk in session.get("sublinks", [])]
    if pages:
        code += fill('''

USER_PAGES = __PAGES__


@pytest.mark.parametrize("url", [p[1] for p in USER_PAGES], ids=[p[0] for p in USER_PAGES])
def test_user_view(login_user: Page, login_url: str, url: str):
    """Verify the logged-in user can open a page without being sent back to login."""
    response = login_user.goto(url)
    assert response is None or response.status < 400, f"{url} returned {response.status}"
    assert not is_login_url(login_user.url, login_url), f"Redirected to login from {url}"
''', PAGES=pages)

    if session.get("has_logout"):
        code += '''

def test_user_logout(login_user: Page, login_url: str):
    """Verify logging out ends the session."""
    page = login_user
    logout = page.locator(LOGOUT_SELECTOR).first
    expect(logout).to_be_visible()
    logout.click()
    page.wait_for_load_state()
    expect(page.locator(LOGOUT_SELECTOR).first).to_be_hidden()
'''
        if ctx.is_protected_target(ctx.user_target_url):
            code += '''    response = page.goto(USER_LANDING)
    assert access_blocked(page.url, response.status if response else None, USER_LANDING, login_url, password_field_visible(page)), \\
        f"Still able to open {USER_LANDING} after logging out"
'''
    code += _logged_in_form_tests(ctx, user_forms, "login_user", "user_form")
    ctx.write_test("e2e", "test_user_session.py", code)


