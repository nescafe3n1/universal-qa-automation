def _modal_trigger_expr(modal: dict) -> str:
    """Python source (with __TRIG__/__TTEXT__ placeholders) that finds the element opening the modal."""
    expr = "page.locator(__TRIG__)"
    if modal["trigger"].get("text"):
        expr += '.filter(has_text=text_re(__TTEXT__))'
    return expr


def write_forms(ctx: SuiteContext) -> None:
    forms = ctx.scan["components"].get("forms") or []
    modal = ctx.scan["components"].get("modal") or {}
    modal_form = modal.get("form")
    if not forms and not modal_form:
        return
    doc = ("Non-login forms, on the page and inside popup dialogs: every field is filled and checked, then the form "
           "is SUBMITTED and the page's response is checked (--submit-forms)."
           if ctx.submit_forms else
           "Non-login forms, on the page and inside popup dialogs: every field is filled and checked. "
           "Forms are NOT submitted (regenerate with --submit-forms to submit them).")
    code = header(doc, ctx, PAGE_IMPORTS + "\n\nfrom qa_forms import (SUBMIT_BUTTON, check_empty_submit, check_valid_submit,\n"
                  "                      fill_form, submit_and_observe)", "pytest.mark.e2e")

    for n, frm in enumerate(forms, start=1):
        if not frm.get("fillable_count", frm.get("input_count", 0)):
            continue
        goto = fill('''    page.goto(__URL__)
    form = page.locator("form").nth(__IDX__)
    expect(form).to_be_visible()
''', URL=frm["page_url"], IDX=frm["index"])
        code += _form_tests(f"group_{n}", goto, frm, ctx.submit_forms)

    if modal_form and modal_form.get("fillable_count"):
        goto = fill('''    page.goto(__URL__)
    trigger = ''' + _modal_trigger_expr(modal) + '''.first
    expect(trigger).to_be_visible()
    trigger.click()
    form = page.locator(__DLG__).first.locator("form").first
    expect(form).to_be_visible()
''', URL=modal["page_url"], TRIG=modal["trigger"]["selector"], TTEXT=modal["trigger"].get("text") or "",
                    DLG=modal["dialog_selector"])
        code += _form_tests("modal", goto, modal_form, ctx.submit_forms, where="in the popup dialog")
    ctx.write_test("e2e", "test_forms.py", code)


def _form_tests(suffix: str, goto: str, frm: dict, submit: bool, where: str = "",
                fixture: str = "page", name: str = "form") -> str:
    """
    Fill test, and (with --submit-forms) a valid-submit test plus an empty-submit test for required fields.
    `fixture` is the Page fixture the test uses ("page", or "login_user" / "login_admin" for logged-in forms).
    Forms that look destructive or spend money (delete, logout, checkout...) are filled but never submitted.
    """
    loc = f" {where}" if where else ""
    arg = f"{fixture}: Page"
    start = "" if fixture == "page" else f"    page = {fixture}\n"
    code = f'''

def test_{name}_inputs_{suffix}({arg}):
    """Verify every field in the form{loc} accepts input{" and its submit control is shown" if frm.get("has_submit") else ""}."""
{start}''' + goto + '''    assert fill_form(form) > 0, "No field in the form could be filled"
'''
    if frm.get("has_submit"):
        code += '''    expect(form.locator(SUBMIT_BUTTON).first).to_be_visible()
'''
    if not (submit and frm.get("has_submit")):
        return code
    if frm.get("unsafe_submit"):
        return code + f"\n\n# test_{name}_submit_{suffix} not generated: the form looks destructive or spends money (delete, logout, checkout...).\n"
    code += f'''

@pytest.mark.write
def test_{name}_submit_{suffix}({arg}):
    """Verify submitting the filled form{loc} gets a visible response and causes no server or JavaScript error."""
{start}''' + goto + '''    fill_form(form)
    check_valid_submit(submit_and_observe(page, form))
'''
    if frm.get("required_count"):
        code += f'''

@pytest.mark.write
def test_{name}_empty_submit_{suffix}({arg}):
    """Verify the empty form{loc} is refused with a visible error (it has required fields)."""
{start}''' + goto + '''    check_empty_submit(submit_and_observe(page, form))
'''
    return code


def _logged_in_form_tests(ctx: SuiteContext, forms: list, fixture: str, name: str) -> str:
    """Form tests for forms found inside the user or admin area; they run with the logged-in page fixture."""
    code = ""
    for n, frm in enumerate(forms, start=1):
        goto = fill('''    page.goto(__URL__)
    form = page.locator("form").nth(__IDX__)
    expect(form).to_be_visible()
''', URL=frm["page_url"], IDX=frm["index"])
        code += _form_tests(str(n), goto, frm, ctx.submit_forms, where="in the logged-in area", fixture=fixture, name=name)
    return code


def _fillable(forms) -> list:
    return [f for f in forms or [] if f.get("fillable_count", f.get("input_count", 0))]


